import { chromium } from '@playwright/test';
import { mkdir } from 'node:fs/promises';

await mkdir('artifacts', { recursive: true });
const browser = await chromium.launch();
try {
  const context = await browser.newContext({ viewport: { width: 1440, height: 1100 } });
  const page = await context.newPage();
  const errors = [], externalRequests = [];
  page.on('pageerror', error => errors.push(error.message));
  page.on('request', request => { if (!request.url().startsWith('http://127.0.0.1:5173/') && !request.url().startsWith('data:')) externalRequests.push(request.url()); });
  await page.goto('http://127.0.0.1:5173/');
  await page.getByRole('button', { name: 'Confirm this plan' }).waitFor();
  await page.evaluate(() => document.fonts.ready);
  await page.screenshot({ path: 'artifacts/desktop.png', fullPage: true });
  await page.getByRole('button', { name: 'Edit preferences', exact: true }).last().click();
  await page.getByRole('dialog').waitFor();
  await page.screenshot({ path: 'artifacts/preferences.png' });
  await page.keyboard.press('Escape');
  await page.getByRole('button', { name: 'Data connections', exact: true }).click();
  await page.getByRole('button', { name: 'Connect backend', exact: true }).click();
  await page.getByText('Authenticated session', { exact: true }).waitFor();
  await page.screenshot({ path: 'artifacts/connections-desktop.png' });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: 'artifacts/connections-mobile.png', fullPage: true });
  await page.keyboard.press('Escape');
  await page.screenshot({ path: 'artifacts/mobile.png', fullPage: true });
  await page.setViewportSize({ width: 1440, height: 1100 });
  await page.getByRole('button', { name: 'Confirm this plan', exact: true }).click();
  await page.getByRole('button', { name: 'Travel assistant', exact: true }).click();
  await page.getByRole('button', { name: 'Use my confirmed plan', exact: true }).click();
  await page.getByRole('button', { name: 'Show Jain food evidence', exact: true }).click();
  await page.getByRole('heading', { name: 'Food evidence', exact: true }).waitFor();
  await page.screenshot({ path: 'artifacts/assistant-evidence.png' });
  await page.getByRole('button', { name: 'Delay 30 minutes', exact: true }).click();
  await page.getByRole('heading', { name: 'Review this revision', exact: true }).waitFor();
  await page.getByRole('button', { name: 'Accept revision', exact: true }).scrollIntoViewIfNeeded();
  await page.screenshot({ path: 'artifacts/assistant-review.png' });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.getByRole('button', { name: 'Accept revision', exact: true }).scrollIntoViewIfNeeded();
  await page.screenshot({ path: 'artifacts/assistant-mobile.png' });
  await page.keyboard.press('Escape');
  await page.getByRole('button', { name: 'Data connections', exact: true }).click();
  await page.getByRole('button', { name: /^Delete backend trip / }).click();
  await page.getByRole('button', { name: 'Delete backend trip', exact: true }).click();
  await page.keyboard.press('Escape');
  const horizontalOverflow = await page.evaluate(() => document.documentElement.scrollWidth > innerWidth);
  console.log(JSON.stringify({ pageErrors: errors, externalRequests, horizontalOverflow }));
  if (errors.length || externalRequests.length || horizontalOverflow) process.exitCode = 1;
} finally { await browser.close(); }
